export const palette =["#ffffff", "#ffd5e5", "#5d0e2a"] as const;

type ImageSize = { src: string; width: number; height: number };
export type Page = ImageSize & { full: ImageSize; label: string };

// Page images are generated by scripts/prepare-images.mjs, per language.
function pages(project: keyof typeof workManifest, locale: Locale, label: (n: number, total: number) => string): Page[] {
  const entries = workManifest[project][locale];
  return entries.map(({ thumb, full }, i) => ({ ...thumb, full, label: label(i + 1, entries.length) }));
}

export function getContent(locale: Locale) {
  const t = dictionaries[locale];
  const swapClosetPages = pages("swapcloset", locale, (n) => fill(t.projects.swapCloset.pageLabel, { n }));
  const likamiPages = pages("likami", locale, (n, total) => `${String(n).padStart(2, "0")} / ${total}`);

  return {
    ...t,
    locale,
    swapCloset: {
      ...t.projects.swapCloset,
      number: "01",
      title: ["Swap", "Closet."],
      name: "SwapCloset",
      cover: swapClosetPages[0],
      pages: swapClosetPages,
    },
    likami: {
      ...t.projects.likami,
      number: "02",
      title: "Líkami.",
      name: "Líkami",
      cover: likamiPages[0],
      pages: likamiPages,
    },
  };
}

export type Content = ReturnType<typeof getContent>;
